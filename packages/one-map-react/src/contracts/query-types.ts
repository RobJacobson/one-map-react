import type { Point } from "./camera-types.js";
import type { FilterExpression } from "./layer-types.js";
import type { GeoJsonFeature } from "./source-types.js";

/**
 * Screen rectangle for rendered queries, top-left then bottom-right.
 *
 * @remarks
 * The corners are `[x, y]` pairs in logical map-view units, matching
 * react-map-gl. RNMapbox receives them reordered to
 * `[top, left, bottom, right]`.
 */
export type ScreenBounds = readonly [Point, Point];

/**
 * Options for {@link MapRef.queryRenderedFeatures}.
 */
export interface QueryRenderedFeaturesOptions {
  /**
   * Style layer ids the query inspects. Omitted queries every layer.
   * Web rejects a requested id absent from the loaded style; an empty list
   * is forwarded with the renderer's normal semantics.
   */
  readonly layers?: readonly string[];
  /**
   * Filter expression limiting the query results.
   *
   * @remarks
   * The filter is passed through structurally; each renderer validates the
   * operators it supports.
   */
  readonly filter?: FilterExpression;
}

/**
 * Options for {@link MapRef.querySourceFeatures}.
 */
export interface QuerySourceFeaturesOptions {
  /**
   * Layer inside a vector tile source to query.
   *
   * @remarks
   * Ignored for GeoJSON sources. A nonempty name is required for web vector
   * queries. MapLibre Native requires the field; RNMapbox forwards the
   * source-layer list, including an empty list when omitted.
   */
  readonly sourceLayer?: string;
  /**
   * Filter expression limiting the query results.
   *
   * @remarks
   * The filter is passed through structurally; each renderer validates the
   * operators it supports.
   */
  readonly filter?: FilterExpression;
}

/**
 * A feature a map method targets, identified by source and feature id.
 *
 * @remarks
 * `source` is the facade {@link Source} id. `sourceLayer` names the layer
 * inside a vector tile source. `id` is the feature id carried in the source
 * data, not the source or layer id.
 */
export interface FeatureIdentifier {
  /** Id of the source that owns the feature. */
  readonly source: string;
  /** Feature id carried in the source data. */
  readonly id: string | number;
  /** Nonempty layer name required when targeting a vector source. */
  readonly sourceLayer?: string;
}

/**
 * A JSON primitive value accepted in feature state.
 *
 * @remarks
 * `null` and non-finite numbers are excluded by the portable contract; use
 * {@link MapRef.removeFeatureState} to clear a key.
 */
export type FeatureStateValue =
  | boolean
  | number
  | string
  | readonly FeatureStateValue[]
  | { readonly [key: string]: FeatureStateValue };

/**
 * Runtime state merged onto an identified feature.
 *
 * @remarks
 * Values are JSON; `null`, `undefined`, and non-finite numbers are rejected
 * so every backend stores the same shape. MapLibre wrappers drop `null`
 * keys, so the facade forbids them instead of forking behavior.
 */
export type FeatureState = Readonly<Record<string, FeatureStateValue>>;

/**
 * Cluster methods shared by every adapter.
 *
 * @remarks
 * Cluster ids come from cluster features returned by a query; they are
 * generated by the source and can change after a GeoJSON `data` update.
 */
export interface ClusterQueryMethods {
  /**
   * Reads the zoom at which a cluster expands.
   *
   * @param sourceId - Facade id of the clustered GeoJSON source.
   * @param clusterId - Cluster id from a queried cluster feature.
   * @returns The zoom level where the cluster breaks apart.
   * @throws When the source is not a mounted clustered GeoJSON source or the
   * wrapper query fails.
   */
  getClusterExpansionZoom: (
    sourceId: string,
    clusterId: number
  ) => Promise<number>;
  /**
   * Reads the point features inside a cluster.
   *
   * @param sourceId - Facade id of the clustered GeoJSON source.
   * @param clusterId - Cluster id from a queried cluster feature.
   * @param limit - Maximum number of leaves to return.
   * @param offset - Number of leaves to skip, for pagination.
   * @returns The leaf features, in backend order.
   * @throws When the source is not a mounted clustered GeoJSON source or the
   * wrapper query fails.
   */
  getClusterLeaves: (
    sourceId: string,
    clusterId: number,
    limit: number,
    offset: number
  ) => Promise<readonly GeoJsonFeature[]>;
  /**
   * Reads the child clusters of a cluster at the next zoom.
   *
   * @param sourceId - Facade id of the clustered GeoJSON source.
   * @param clusterId - Cluster id from a queried cluster feature.
   * @returns The child cluster features, in backend order.
   * @throws When the source is not a mounted clustered GeoJSON source or the
   * wrapper query fails.
   */
  getClusterChildren: (
    sourceId: string,
    clusterId: number
  ) => Promise<readonly GeoJsonFeature[]>;
}

/**
 * Rendered and source query methods shared by every adapter.
 */
export interface FeatureQueryMethods {
  /**
   * Queries features rendered at a screen point or rectangle.
   *
   * @remarks
   * Only rendered features match: a feature in loaded-but-hidden state does
   * not. An empty successful result resolves to `[]`. Web errors emitted
   * synchronously during dispatch reject the query promise and continue
   * reaching the map's error callback.
   *
   * @param target - `[x, y]` point, `[[left, top], [right, bottom]]`
   * rectangle, or `undefined` for the visible viewport.
   * @param options - Layer ids and filter limiting the query.
   * @returns Matched features in backend order, duplicates preserved.
   * @throws When the map ref is missing, a wrapper result is malformed,
   * a requested web layer is missing, or the renderer rejects the query.
   */
  queryRenderedFeatures: (
    target: Point | ScreenBounds | undefined,
    options?: QueryRenderedFeaturesOptions
  ) => Promise<readonly GeoJsonFeature[]>;
  /**
   * Queries features in the tiles a source loaded.
   *
   * @remarks
   * Results come from loaded tiles for the current viewport and zoom,
   * including features hidden by layer styling. Tile boundaries can clip
   * geometries or duplicate features. MapLibre Native uses the wrapper
   * GeoJSON `getData` path, which queries loaded source tiles on both OSes.
   *
   * @param sourceId - Facade id of the mounted source.
   * @param options - Vector source layer and filter limiting the query.
   * @returns Matched features in backend order, duplicates preserved.
   * @throws When the source is missing, a native source ref required by the
   * adapter is not mounted through a facade `Source`, the adapter cannot
   * query that source family, or a required source layer is absent. Web
   * errors emitted synchronously during dispatch also reject.
   */
  querySourceFeatures: (
    sourceId: string,
    options?: QuerySourceFeaturesOptions
  ) => Promise<readonly GeoJsonFeature[]>;
}

/**
 * Feature-state methods shared by every adapter.
 */
export interface FeatureStateMethods {
  /**
   * Merges state onto an identified feature.
   *
   * @remarks
   * Resolution acknowledges dispatch, not a completed repaint. Feature state
   * resets when an owned source is recreated or the style is replaced.
   * Native adapters clear facade-written targets after a fully rendered frame
   * or before the replacement source's first state operation, ordered after
   * pending prior writes. Automatic reset failures reach the map error callback.
   * Pending operations against a detached or replaced source reject. Empty
   * retired native records are forgotten after their queues settle; later calls
   * for those ids use the selected adapter's normal source validation. Written
   * family journals remain until cleanup succeeds. Reset failures reject later
   * state calls until another source lifetime or style begins.
   *
   * @param identifier - Source, feature id, and optional vector source layer.
   * @param state - JSON values merged onto the feature's state.
   * @returns A promise that adopts the wrapper call.
   * @throws When the identifier is malformed, a state value is `null`,
   * `undefined`, or a non-finite number, the map ref is missing, or the
   * wrapper call fails.
   */
  setFeatureState: (
    identifier: FeatureIdentifier,
    state: FeatureState
  ) => Promise<void>;
  /**
   * Reads the merged state of an identified feature.
   *
   * @remarks
   * MapLibre wrappers apply removals on the next rendered frame, so a read
   * immediately after a removal may still report the removed keys.
   *
   * @param identifier - Source, feature id, and optional vector source layer.
   * @returns The feature's state; `{}` when the feature has no state. Native
   * nullish state is normalized; absent web read results reject.
   * @throws When the identifier is malformed, the map ref is missing, or the
   * wrapper call fails.
   */
  getFeatureState: (identifier: FeatureIdentifier) => Promise<FeatureState>;
  /**
   * Removes a state key, or the feature's entire state.
   *
   * @remarks
   * Resolution acknowledges dispatch. MapLibre wrappers apply removals on
   * the next rendered frame.
   *
   * @param identifier - Source, feature id, and optional vector source layer.
   * @param key - State key to remove. Omitted removes the whole state.
   * @returns A promise that adopts the wrapper call.
   * @throws When the identifier is malformed, the map ref is missing, or the
   * wrapper call fails.
   */
  removeFeatureState: (
    identifier: FeatureIdentifier,
    key?: string
  ) => Promise<void>;
}
